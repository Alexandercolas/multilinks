create table if not exists public.account_moderation (
  user_id uuid primary key references auth.users(id) on delete cascade,
  suspended_at timestamptz,
  suspended_by uuid references auth.users(id) on delete set null,
  suspension_reason text check (suspension_reason is null or char_length(suspension_reason) <= 500),
  updated_at timestamptz not null default now()
);

create table if not exists public.profile_reports (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  reporter_id uuid references auth.users(id) on delete set null,
  reason text not null check (reason in ('spam','abuse','impersonation','inappropriate','copyright','other')),
  description text not null default '' check (char_length(description) <= 1000),
  status text not null default 'pending' check (status in ('pending','reviewing','resolved','dismissed')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  resolution_note text check (resolution_note is null or char_length(resolution_note) <= 1000),
  created_at timestamptz not null default now()
);

create index if not exists profile_reports_status_created_idx on public.profile_reports (status, created_at desc);

create table if not exists public.admin_action_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  target_user_id uuid references auth.users(id) on delete set null,
  action text not null check (action in ('suspend_user','reactivate_user','review_report','dismiss_report')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_action_logs_created_idx on public.admin_action_logs (created_at desc);

create table if not exists public.support_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  email text not null check (char_length(email) between 5 and 320),
  subject text not null check (char_length(subject) between 3 and 120),
  message text not null check (char_length(message) between 10 and 2000),
  status text not null default 'open' check (status in ('open','in_progress','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists support_requests_status_created_idx on public.support_requests (status, created_at desc);

create table if not exists public.link_daily_clicks (
  link_id uuid not null references public.links(id) on delete cascade,
  day date not null default current_date,
  clicks integer not null default 0 check (clicks >= 0),
  primary key (link_id, day)
);

create table if not exists public.request_rate_limits (
  request_key text primary key,
  window_started timestamptz not null default now(),
  hit_count integer not null default 1 check (hit_count > 0)
);

alter table public.account_moderation enable row level security;
alter table public.profile_reports enable row level security;
alter table public.admin_action_logs enable row level security;
alter table public.support_requests enable row level security;
alter table public.link_daily_clicks enable row level security;
alter table public.request_rate_limits enable row level security;

create or replace function public.profile_is_available(target_profile uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = target_profile and published = true
  ) and not exists (
    select 1 from public.account_moderation
    where user_id = target_profile and suspended_at is not null
  )
$$;

