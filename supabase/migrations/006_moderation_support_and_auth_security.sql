  or exists (
    select 1 from public.links
    where links.id = link_daily_clicks.link_id and links.profile_id = auth.uid()
  )
);

create or replace function public.account_is_suspended()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.account_moderation
    where user_id = auth.uid() and suspended_at is not null
  )
$$;

create or replace function public.check_request_rate_limit(target_key text, max_hits integer, window_seconds integer)
returns boolean language plpgsql security definer set search_path = public
as $$
declare allowed boolean;
begin
  if target_key is null or char_length(target_key) < 16 or max_hits < 1 or window_seconds < 1 then return false; end if;
  insert into public.request_rate_limits (request_key, window_started, hit_count)
  values (target_key, now(), 1)
  on conflict (request_key) do update set
    window_started = case when request_rate_limits.window_started < now() - make_interval(secs => window_seconds) then now() else request_rate_limits.window_started end,
    hit_count = case when request_rate_limits.window_started < now() - make_interval(secs => window_seconds) then 1 else request_rate_limits.hit_count + 1 end
  returning hit_count <= max_hits into allowed;
  return allowed;
end;
$$;

create or replace function public.admin_set_user_suspension(target_user uuid, should_suspend boolean, reason text default null)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Not authorized'; end if;
  if target_user = auth.uid() then raise exception 'Administrators cannot suspend themselves'; end if;
  if should_suspend and (reason is null or char_length(trim(reason)) < 3) then raise exception 'A suspension reason is required'; end if;

  insert into public.account_moderation (user_id, suspended_at, suspended_by, suspension_reason, updated_at)
  values (target_user, case when should_suspend then now() else null end, case when should_suspend then auth.uid() else null end, case when should_suspend then left(trim(reason), 500) else null end, now())
  on conflict (user_id) do update set suspended_at = excluded.suspended_at, suspended_by = excluded.suspended_by,
    suspension_reason = excluded.suspension_reason, updated_at = now();

  insert into public.admin_action_logs (actor_id, target_user_id, action, details)
  values (auth.uid(), target_user, case when should_suspend then 'suspend_user' else 'reactivate_user' end,
    jsonb_build_object('reason', case when should_suspend then left(trim(reason), 500) else null end));
end;
$$;

drop policy if exists "Public profiles are visible" on public.profiles;
create policy "Public profiles are visible" on public.profiles for select using (
  auth.uid() = id or public.is_admin()
  or public.profile_is_available(id)
);

create or replace function public.record_profile_view(target_profile uuid)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if public.profile_is_available(target_profile) then
    insert into public.profile_daily_views (profile_id, day, views)
    values (target_profile, current_date, 1)
    on conflict (profile_id, day) do update set views = profile_daily_views.views + 1;
  end if;
end;
$$;

create or replace function public.public_link_destination(target_link uuid)
returns text language sql stable security definer set search_path = public
as $$
  select links.url from public.links
  where links.id = target_link and links.active = true
    and public.profile_is_available(links.profile_id)
$$;

create or replace function public.record_link_click(target_link uuid)
returns text language plpgsql security definer set search_path = public
as $$
declare destination text;
begin
  update public.links set clicks = clicks + 1
  where id = target_link and active = true and public.profile_is_available(profile_id)
  returning url into destination;

  if destination is not null then
    insert into public.link_daily_clicks (link_id, day, clicks) values (target_link, current_date, 1)
    on conflict (link_id, day) do update set clicks = link_daily_clicks.clicks + 1;
  end if;
  return destination;
end;
$$;

